import { useEffect, useState } from 'react';

/** Aktuelle Zeit, alle `intervalMs` neu – für relative Angaben wie „vor 3 Min.“. */
export function useNow(intervalMs = 30_000): Date {
  const [now, setNow] = useState(() => new Date());
  useEffect(() => {
    const timer = setInterval(() => {
      setNow(new Date());
    }, intervalMs);
    return () => {
      clearInterval(timer);
    };
  }, [intervalMs]);
  return now;
}
